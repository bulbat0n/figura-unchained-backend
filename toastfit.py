_ADVANCES = {" ": 4}
for _width, _chars in _GLYPHS.items():
    for _char in _chars:
        _ADVANCES[_char] = _width


def advance(char):
    return _ADVANCES.get(char, FALLBACK_ADVANCE)


def is_exact(text):
    return all(char in _ADVANCES or char == "\n" for char in text)


def split_lines(text, max_width=MAX_WIDTH):
    lines, start, length = [], 0, len(text)
    while start < length:
        width, last_space, visible, end = 0, -1, False, length
        for index in range(start, length):
            char = text[index]
            if char == "\n":
                end = index
                break
            if char == " ":
                last_space = index
            width += advance(char)
            if visible and width > max_width:
                end = last_space if last_space != -1 else index
                break
            visible = visible or advance(char) != 0
        lines.append(text[start:end])
        start = end + (1 if end < length and text[end] in " \n" else 0)
    return lines


def problems(title, message=""):
    found = []
    for name, text in (("title", title), ("text", message)):
        count = len(split_lines(text)) if text.strip() else 0
        if count > MAX_LINES:
            found.append(f"{name} takes {count} lines, the toast fits {MAX_LINES}")
    return found


def fits(title, message=""):
    return not problems(title, message)
